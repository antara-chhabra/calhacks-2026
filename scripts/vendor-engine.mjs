#!/usr/bin/env node
// Copy packages/engine/src/parimutuel.ts into spacetime/src/vendor/ (ADR-019, Q-009), so the module can build
// without a workspace import. parimutuel.ts is kept import-free for exactly this reason.
//   node scripts/vendor-engine.mjs           copy
//   node scripts/vendor-engine.mjs --check   exit 1 if the vendored copy is missing or stale
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/engine/src/parimutuel.ts');
const dest = join(root, 'spacetime/src/vendor/parimutuel.ts');
const header = '// GENERATED by scripts/vendor-engine.mjs from packages/engine/src/parimutuel.ts. Do not edit.\n';
const body = readFileSync(src, 'utf8');
if (/^\s*import\s/m.test(body)) {
  console.error('vendor-engine: parimutuel.ts must stay import-free (ADR-019)');
  process.exit(1);
}
const want = header + body;
if (process.argv.includes('--check')) {
  const ok = existsSync(dest) && readFileSync(dest, 'utf8') === want;
  console.log(ok ? 'vendor-engine: up to date' : 'vendor-engine: stale or missing; run `npm run vendor-engine`');
  process.exit(ok ? 0 : 1);
}
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, want);
console.log(`vendor-engine: wrote ${dest.slice(root.length + 1)}`);
